    role_code_key TEXT;
    permission_code_key TEXT;
    permission_name TEXT;
BEGIN
    FOR role_code_key IN SELECT jsonb_object_keys(role_permissions)
    LOOP
        FOR permission_code_key IN SELECT jsonb_array_elements_text(role_permissions -> role_code_key)
        LOOP
            permission_name := initcap(replace(permission_code_key, '_', ' '));

            INSERT INTO permissions (permission_code, name, description)
            VALUES (permission_code_key, permission_name, permission_name)
            ON CONFLICT (permission_code) DO NOTHING;

            INSERT INTO role_permissions (role_id, permission_id, created_at)
            SELECT r.id, p.id, COALESCE(p.created_at, CURRENT_TIMESTAMP)
            FROM roles r
            JOIN permissions p ON p.permission_code = permission_code_key
            WHERE r.role_code = role_code_key
            ON CONFLICT (role_id, permission_id) DO NOTHING;
        END LOOP;
    END LOOP;
END $$;