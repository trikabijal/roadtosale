            "USER_CREATE", "USER_EDIT", "USER_PASSWORD_RESET", "USER_DELETE", "USER_LIST", "USER_DOWNLOAD"
        ],
        "SUBDEPT_ADMIN": [
            "USER_CREATE", "USER_EDIT", "USER_PASSWORD_RESET", "USER_DELETE", "USER_LIST", "USER_DOWNLOAD",
            "CHECKSHEET_MANAGEMENT_LIST", "CHECKSHEET_MANAGEMENT_DETAIL_CREATE",
